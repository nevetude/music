"""Отображаемое имя артиста.

Genius хранит два варианта: `name` (может включать дизамбигуатор вроде
"Alex (Rapper)") и `base_name` (то же самое имя без дизамбигуатора). На
фронтенде мы везде показываем базовое имя — этот модуль даёт единую точку,
где это решается, чтобы не дублировать `base_name or name` по всем местам,
где артист попадает в ответ API.
"""


def display_name(name: str, base_name: str | None) -> str:
    return base_name or name
